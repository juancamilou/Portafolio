// ============ NAV SCROLL STATE + PROGRESS BAR ============
const nav = document.getElementById("nav");
const progressBar = document.getElementById("progressBar");

function onScroll() {
  nav.classList.toggle("scrolled", window.scrollY > 20);
  const docHeight = document.documentElement.scrollHeight - window.innerHeight;
  const progress = docHeight > 0 ? (window.scrollY / docHeight) * 100 : 0;
  progressBar.style.width = progress + "%";
}
window.addEventListener("scroll", onScroll, { passive: true });
onScroll();

// ============ SCROLLSPY ============
const sections = document.querySelectorAll("main section[id]");
const navLinkEls = document.querySelectorAll(".nav-links a");
const spyObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        navLinkEls.forEach((link) => {
          link.classList.toggle(
            "active",
            link.getAttribute("href") === "#" + entry.target.id,
          );
        });
      }
    });
  },
  { rootMargin: "-45% 0px -50% 0px" },
);
sections.forEach((s) => spyObserver.observe(s));

// ============ SCROLL REVEAL ============
const revealTargets = document.querySelectorAll(
  ".about-grid, .skills-grid, .project, .contact-title, .contact-links",
);
revealTargets.forEach((el) => el.classList.add("reveal"));
const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in-view");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.15 },
);
revealTargets.forEach((el) => revealObserver.observe(el));

// ============ SKILL TAGS — STAGGERED WAVE REVEAL ============
document.querySelectorAll(".skill-group").forEach((group) => {
  const tags = group.querySelectorAll(".tag");
  const groupObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          tags.forEach((tag, i) => {
            setTimeout(
              () => tag.classList.add("tag-in"),
              reduceMotion ? 0 : i * 60,
            );
          });
          groupObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.2 },
  );
  groupObserver.observe(group);
});

// ============ COUNT UP STATS ============
const counters = document.querySelectorAll(".stat-num");
const countObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = parseInt(el.getAttribute("data-count"), 10);
        const duration = 1000;
        const start = performance.now();
        function tick(now) {
          const p = Math.min((now - start) / duration, 1);
          const eased = 1 - Math.pow(1 - p, 3);
          el.textContent = Math.floor(eased * target);
          if (p < 1) requestAnimationFrame(tick);
          else el.textContent = target;
        }
        requestAnimationFrame(tick);
        countObserver.unobserve(el);
      }
    });
  },
  { threshold: 0.5 },
);
counters.forEach((el) => countObserver.observe(el));

// ============ HERO MOUSE GLOW ============
const heroBg = document.getElementById("heroBg");
const heroSection = document.querySelector(".hero");
const hoverCapable = window.matchMedia("(hover: hover)").matches;
if (hoverCapable) {
  heroSection.addEventListener("mousemove", (e) => {
    const rect = heroSection.getBoundingClientRect();
    const x = ((e.clientX - rect.left) / rect.width) * 100;
    const y = ((e.clientY - rect.top) / rect.height) * 100;
    heroBg.style.setProperty("--mx", x + "%");
    heroBg.style.setProperty("--my", y + "%");
  });
}

// ============ TILT 3D ON PHOTO ============
if (hoverCapable && !reduceMotion) {
  document.querySelectorAll(".tilt").forEach((el) => {
    el.addEventListener("mousemove", (e) => {
      const rect = el.getBoundingClientRect();
      const px = (e.clientX - rect.left) / rect.width - 0.5;
      const py = (e.clientY - rect.top) / rect.height - 0.5;
      el.style.setProperty("--ry", px * 14 + "deg");
      el.style.setProperty("--rx", -py * 14 + "deg");
    });
    el.addEventListener("mouseleave", () => {
      el.style.setProperty("--rx", "0deg");
      el.style.setProperty("--ry", "0deg");
    });
  });
}

// ============ MAGNETIC BUTTONS ============
if (hoverCapable && !reduceMotion) {
  document.querySelectorAll(".magnetic").forEach((el) => {
    el.addEventListener("mousemove", (e) => {
      const rect = el.getBoundingClientRect();
      const x = e.clientX - rect.left - rect.width / 2;
      const y = e.clientY - rect.top - rect.height / 2;
      el.style.transform = `translate(${x * 0.25}px, ${y * 0.35}px)`;
    });
    el.addEventListener("mouseleave", () => {
      el.style.transform = "";
    });
  });
}

// ============ SCRAMBLE TEXT ON NAME ============
(function scrambleName() {
  const el = document.getElementById("scrambleName");
  const finalText = el.textContent;
  if (reduceMotion) return;
  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
  let frame = 0;
  const totalFrames = 22;
  function render() {
    let out = "";
    for (let i = 0; i < finalText.length; i++) {
      const charProgress = frame - i * 1.4;
      if (finalText[i] === " ") {
        out += " ";
        continue;
      }
      if (charProgress > totalFrames * 0.5) {
        out += finalText[i];
      } else if (charProgress > 0) {
        out += chars[Math.floor(Math.random() * chars.length)];
      } else {
        out += "";
      }
    }
    el.textContent = out;
    frame++;
    if (frame < totalFrames + finalText.length) {
      requestAnimationFrame(render);
    } else {
      el.textContent = finalText;
    }
  }
  setTimeout(() => requestAnimationFrame(render), 550);
})();

